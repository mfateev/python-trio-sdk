@workflow.defn
class SimpleE2EWorkflow:
    """Simple workflow for E2E replay testing."""

    @workflow.run
    async def run(self, name: str) -> str:
        await workflow.sleep(0.1)
        return f"Hello, {name}!"


@workflow.defn(name="SimpleE2EWorkflow")
class SimpleE2EWorkflowModified:
    """Modified version to trigger nondeterminism on replay.

    Uses the same Temporal name as SimpleE2EWorkflow to allow replaying
    the original workflow's history with this modified code.
    """

    @workflow.run
    async def run(self, name: str) -> str:
        # Different code path - extra sleep causes nondeterminism during replay
        await workflow.sleep(0.1)
        await workflow.sleep(0.2)
        return f"Hello, {name}!"


@pytest.mark.temporal_server
@pytest.mark.trio
async def test_replayer_e2e_complete_workflow(
    trio_client: Any,
) -> None:
    """E2E: Run workflow, fetch history, replay successfully."""
    task_queue = f"replay-e2e-{uuid.uuid4()}"
    workflow_id = f"replay-wf-{uuid.uuid4()}"

    # Run the workflow using a nursery-managed worker
    async with trio.open_nursery() as nursery:
        w = Worker(
            trio_client,
            task_queue=task_queue,
            workflows=[SimpleE2EWorkflow],
        )
        nursery.start_soon(w.run)

        handle = await trio_client.start_workflow(
            "SimpleE2EWorkflow",
            "Temporal",
            id=workflow_id,
            task_queue=task_queue,
        )
        result = await handle.result(timeout=15)
        assert result == "Hello, Temporal!"

        # Shutdown worker
        await w.shutdown()
        nursery.cancel_scope.cancel()

    # Fetch history and replay
    history = await handle.fetch_history()
    await Replayer(workflows=[SimpleE2EWorkflow]).replay_workflow(history)


@pytest.mark.temporal_server
@pytest.mark.trio
async def test_replayer_e2e_nondeterminism(
    trio_client: Any,
) -> None:
    """E2E: Run workflow, replay with modified code -> nondeterminism detected."""
    task_queue = f"replay-e2e-nondet-{uuid.uuid4()}"
    workflow_id = f"replay-nondet-{uuid.uuid4()}"

    # Run the workflow
