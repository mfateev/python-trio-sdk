@activity.defn
async def say_hello(name: str) -> str:
    return f"Hello, {name}!"


@workflow.defn
class SayHelloWorkflow:
    """Simple workflow that matches the JSON fixture's SayHelloWorkflow.

    The JSON fixture was generated by the sdk-python test suite with this
    exact workflow type name. The workflow calls the say_hello activity.
    """

    def __init__(self) -> None:
        self._waiting = False
        self._finish = False

    @workflow.run
    async def run(self, params: Any) -> str:
        # Extract name from params (can be SayHelloParams or raw)
        name = params.name if hasattr(params, "name") else str(params)

        result = await workflow.execute_activity(
            say_hello,
            name,
            schedule_to_close_timeout=timedelta(seconds=60),
        )

        # Wait if requested
        if hasattr(params, "should_wait") and params.should_wait:
            self._waiting = True
            await workflow.wait_condition(lambda: self._finish)
            self._waiting = False

        # Raise if requested
        if hasattr(params, "should_error") and params.should_error:
            raise RuntimeError("Intentional error")

        return result

    @workflow.signal
    def finish(self) -> None:
        self._finish = True

    @workflow.query
    def waiting(self) -> bool:
        return self._waiting


@dataclass
class SayHelloParams:
    name: str
    should_wait: bool = False
    should_error: bool = False
    should_cause_nondeterminism: bool = False


